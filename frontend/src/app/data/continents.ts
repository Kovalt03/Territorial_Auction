// Catmull-Rom → cubic Bezier (closed loop)
function smooth(pts: [number, number][]): string {
  const n = pts.length;
  let d = `M ${pts[0][0]},${pts[0][1]}`;
  for (let i = 0; i < n; i++) {
    const [x0, y0] = pts[(i - 1 + n) % n];
    const [x1, y1] = pts[i];
    const [x2, y2] = pts[(i + 1) % n];
    const [x3, y3] = pts[(i + 2) % n];
    const c1x = +(x1 + (x2 - x0) / 6).toFixed(1);
    const c1y = +(y1 + (y2 - y0) / 6).toFixed(1);
    const c2x = +(x2 - (x3 - x1) / 6).toFixed(1);
    const c2y = +(y2 - (y3 - y1) / 6).toFixed(1);
    d += ` C ${c1x},${c1y} ${c2x},${c2y} ${x2},${y2}`;
  }
  return d + ' Z';
}

